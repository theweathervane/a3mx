#!/usr/bin/env python3
"""The SDL3 GPU renderer's shaders (src/platform/ge_sdlgpu.c), compiled once and kept in the repository.

SDL_GPU takes shaders already compiled for each API: SPIR-V for Vulkan, DXIL for Direct3D 12, MSL
(source) for Metal. A normal build needs none of the compilers: this writes
src/platform/gpu_shaders.h (byte arrays, and the Metal source as text) from
src/platform/gpu_shaders/*.hlsl and *.metal, and that file is committed. Run it again after changing
a shader (maintainers only):

    python tools/gpu_shaders.py [--dxc PATH]

Compilers: DXIL with the Windows SDK's dxc.exe (it signs DXIL with the dxil.dll beside it) or any
dxc; SPIR-V with a dxc built with SPIR-V output (Microsoft's release of DirectXShaderCompiler, pinned
in tools/data/pins.json, in .tools/dxc/). Without a SPIR-V compiler the header says so
(GPU_SHADERS_SPIRV 0) and the Vulkan choice falls back to OpenGL. Standard library only.
"""
import glob, os, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src', 'platform', 'gpu_shaders')
OUT = os.path.join(ROOT, 'src', 'platform', 'gpu_shaders.h')
TOOLS = os.environ.get('A3MX_TOOLS_DIR') or os.path.join(ROOT, '.tools')
SHADERS = [('ge_draw', 'vs_main', 'vs_6_0', 'vs'), ('ge_draw', 'fs_main', 'ps_6_0', 'fs'),
           ('ge_present', 'vs_main', 'vs_6_0', 'vs'), ('ge_present', 'fs_main', 'ps_6_0', 'fs')]


def sdk_dxc():
    base = r'C:\Program Files (x86)\Windows Kits\10\bin'
    found = sorted(glob.glob(os.path.join(base, '10.*', 'x64', 'dxc.exe')))
    return found[-1] if found else None


def release_dxc():
    for p in glob.glob(os.path.join(TOOLS, 'dxc', '**', 'dxc.exe' if os.name == 'nt' else 'dxc'), recursive=True):
        if os.sep + 'x64' + os.sep in p or os.name != 'nt': return p
    return None


def compile_one(dxc, src, entry, profile, spirv):
    with tempfile.TemporaryDirectory() as d:
        out = os.path.join(d, 'out.bin')
        cmd = [dxc, '-T', profile, '-E', entry, '-O3', '-Fo', out, src]
        if spirv: cmd[1:1] = ['-spirv', '-fspv-target-env=vulkan1.0']
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            return None, (r.stderr or r.stdout).strip()
        return open(out, 'rb').read(), ''


def c_array(name, data):
    lines = ['static const unsigned char %s[%d] = {' % (name, max(len(data), 1))]
    for i in range(0, len(data), 20):
        lines.append('    ' + ', '.join('0x%02x' % b for b in data[i:i + 20]) + ',')
    if not data: lines.append('    0')
    lines.append('};')
    return '\n'.join(lines)


def c_string(name, text):
    out = ['static const char %s[] =' % name]
    for line in text.split('\n'):
        out.append('    "%s\\n"' % line.replace('\\', '\\\\').replace('"', '\\"'))
    out[-1] += ';'
    return '\n'.join(out)


def main():
    a = sys.argv[1:]
    dxil_dxc = a[a.index('--dxc') + 1] if '--dxc' in a else (sdk_dxc() or release_dxc())
    spirv_dxc = release_dxc()
    if not dxil_dxc:
        print('ERROR: no dxc (the Windows SDK\'s, or .tools/dxc/)'); return 1
    parts = ['/* Generated by tools/gpu_shaders.py from src/platform/gpu_shaders/: do not edit. The SDL3 GPU',
             ' * renderer\'s shaders (ge_sdlgpu.c): DXIL (Direct3D 12), SPIR-V (Vulkan), MSL (Metal). */',
             '#pragma once', '']
    have_spirv = 1 if spirv_dxc else 0
    for stem, entry, profile, kind in SHADERS:
        src = os.path.join(SRC, stem + '.hlsl')
        data, err = compile_one(dxil_dxc, src, entry, profile, False)
        if data is None: print('ERROR: %s %s (DXIL): %s' % (stem, entry, err)); return 1
        parts.append(c_array('%s_%s_dxil' % (stem, kind), data))
        if spirv_dxc:
            data, err = compile_one(spirv_dxc, src, entry, profile, True)
            if data is None: print('ERROR: %s %s (SPIR-V): %s' % (stem, entry, err)); return 1
        else:
            data = b''
        parts.append(c_array('%s_%s_spirv' % (stem, kind), data))
        print('  %s %s: DXIL%s' % (stem, entry, ', SPIR-V' if spirv_dxc else ''))
    for stem in ('ge_draw', 'ge_present'):
        parts.append(c_string('%s_msl' % stem, open(os.path.join(SRC, stem + '.metal'), encoding='utf-8').read().rstrip('\n')))
    parts.append('#define GPU_SHADERS_SPIRV %d   /* 0: made without a SPIR-V compiler (no Vulkan) */' % have_spirv)
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(parts) + '\n')
    print('wrote %s (DXIL with %s%s)' % (os.path.relpath(OUT, ROOT), dxil_dxc, '; SPIR-V with %s' % spirv_dxc if spirv_dxc else '; no SPIR-V compiler'))
    return 0


if __name__ == '__main__':
    sys.exit(main())
